from __future__ import annotations

from src.evaluation.reporting.entities.executive_summary import (
    ExecutiveSummary,
)
from src.evaluation.reporting.utils.markdown_rendering_utils import (
    MarkdownRenderingUtils,
)


class ExecutiveSummaryMarkdownRenderer:
    """
    Renders executive summaries as Markdown.
    """

    def __init__(
        self,
        *,
        utils: MarkdownRenderingUtils | None = None,
    ) -> None:
        self._utils = (
            utils
            or MarkdownRenderingUtils()
        )

    def render(
        self,
        *,
        summary: ExecutiveSummary,
    ) -> str:
        sections = [
            f"# {summary.title}",
            "",
            "## Overall Assessment",
            summary.overall_assessment,
            "",
            "## KPI Summary",
            self._utils.render_kpi_table(
                rows={
                    "Overall Score": summary.overall_score,
                    "Pass Rate": summary.pass_rate,
                    "Total Runs": summary.total_runs,
                    "Average Score": summary.average_score,
                    "Best Score": summary.best_score,
                    "Risk Level": summary.risk_level,
                    "Trend Direction": (
                        None
                        if summary.trend_direction is None
                        else str(summary.trend_direction)
                    ),
                    "Confidence Level": summary.confidence_level,
                    "Recommendation": summary.recommendation,
                    "Generated By": summary.generated_by,
                },
            ),
            "",
            self._utils.render_list_section(
                title="Key Findings",
                values=summary.key_findings,
            ),
            "",
            self._utils.render_list_section(
                title="Strengths",
                values=summary.strengths,
            ),
            "",
            self._utils.render_list_section(
                title="Weaknesses",
                values=summary.weaknesses,
            ),
            "",
            self._utils.render_list_section(
                title="Recommendations",
                values=summary.recommendations,
            ),
        ]

        if summary.notes is not None:
            sections.extend(
                [
                    "",
                    "## Notes",
                    summary.notes,
                ]
            )

        return "\n".join(
            sections,
        ).strip() + "\n"