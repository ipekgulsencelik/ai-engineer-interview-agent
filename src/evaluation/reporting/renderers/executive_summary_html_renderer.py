from __future__ import annotations

from src.evaluation.ops.entities.executive_summary import (
    ExecutiveSummary,
)
from src.evaluation.ops.exporters.html_rendering_utils import (
    HTMLRenderingUtils,
)


class ExecutiveSummaryHTMLRenderer:
    """
    Renders executive summaries as HTML.
    """

    def __init__(
        self,
        *,
        utils: HTMLRenderingUtils | None = None,
    ) -> None:
        self._utils = (
            utils
            or HTMLRenderingUtils()
        )

    def render(
        self,
        *,
        summary: ExecutiveSummary,
    ) -> str:
        body = "\n".join(
            [
                self._utils.h1(
                    summary.title,
                ),
                self._utils.section(
                    title="Overall Assessment",
                    content=self._utils.paragraph(
                        summary.overall_assessment,
                    ),
                ),
                self._utils.section(
                    title="KPI Summary",
                    content=self._utils.table(
                        rows={
                            "Overall Score": summary.overall_score,
                            "Pass Rate": summary.pass_rate,
                            "Total Runs": summary.total_runs,
                            "Average Score": summary.average_score,
                            "Best Score": summary.best_score,
                            "Risk Level": summary.risk_level,
                            "Trend Direction": (
                                None
                                if summary.trend_direction is None
                                else str(summary.trend_direction)
                            ),
                            "Confidence Level": (
                                summary.confidence_level
                            ),
                            "Recommendation": (
                                summary.recommendation
                            ),
                            "Generated By": summary.generated_by,
                        },
                    ),
                ),
                self._utils.section(
                    title="Key Findings",
                    content=self._utils.list(
                        values=summary.key_findings,
                    ),
                ),
                self._utils.section(
                    title="Strengths",
                    content=self._utils.list(
                        values=summary.strengths,
                    ),
                ),
                self._utils.section(
                    title="Weaknesses",
                    content=self._utils.list(
                        values=summary.weaknesses,
                    ),
                ),
                self._utils.section(
                    title="Recommendations",
                    content=self._utils.list(
                        values=summary.recommendations,
                    ),
                ),
                (
                    ""
                    if summary.notes is None
                    else self._utils.section(
                        title="Notes",
                        content=self._utils.paragraph(
                            summary.notes,
                        ),
                    )
                ),
            ]
        )

        return self._utils.document(
            title=summary.title,
            body=body,
        )